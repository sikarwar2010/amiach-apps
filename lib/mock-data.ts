export function getListingById(id: string) {
  return listings.find((l) => l.id === id || l.slug === id);
}

export function getSellerById(id: string) {
  return sellers.find((s) => s.id === id || s.slug === id);
}

export function getCategoryById(id: string) {
  return categories.find((c) => c.id === id || c.slug === id);
}

export function getLocationById(id: string) {
  return locations.find((l) => l.id === id);
}

export function getRelatedListings(listing: InventoryLot, limit = 4) {
  return listings
    .filter((l) => l.id !== listing.id && l.categoryId === listing.categoryId)
    .slice(0, limit);
}
